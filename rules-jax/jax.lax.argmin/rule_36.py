# if index_dtype is int32, reduction axis size must not exceed the maximum 32-bit signed integer value (Rule 36)

rule_36 = lambda s, v, n=False: (
    s.add(Not(And(And(And(v["arg1_ndim"] > 0, v["arg2_value"] >= 0), v["arg2_value"] < v["arg1_ndim"]), (If(v["arg3_value"] == 3, Select(v["arg1_shape"], v["arg2_value"]) <= 2147483647, True)))) if n else
          And(And(And(v["arg1_ndim"] > 0, v["arg2_value"] >= 0), v["arg2_value"] < v["arg1_ndim"]), (If(v["arg3_value"] == 3, Select(v["arg1_shape"], v["arg2_value"]) <= 2147483647, True))))
)

def rule_36_func(arg1, arg2, arg3, solver=None, neg=False):
    arg1 = next(iter(arg1.values()))
    arg2 = next(iter(arg2.values()))
    arg3 = next(iter(arg3.values()))

    # Invariant learning phase
    if not solver:
        if not isinstance(arg1, np.ndarray):
            return False
        if not (isinstance(arg2, (int, np.integer)) and not isinstance(arg2, bool)):
            return False
        if not (isinstance(arg3, torch.dtype) or isinstance(arg3, tf.dtypes.DType) or isinstance(arg3, np.dtype)):
            return False

        # Variable declarations
        solver = Solver()
        arg1_ndim = Int('arg1_ndim')
        arg1_shape = Array('arg1_shape', IntSort(), IntSort())
        arg2_value = Int('arg2_value')
        arg3_value = Int('arg3_value')

        # Value assignments
        solver.add(arg1_ndim == arg1.ndim)
        for i in range(arg1.ndim):
            arg1_shape = Store(arg1_shape, i, arg1.shape[i])
        solver.add(arg2_value == int(arg2))
        solver.add(arg3_value == list_of_available_dtypes.index(np_dtype(arg3)))

        # Constraints for rule 36
        rule_36(solver, {'arg1_ndim': arg1_ndim, 'arg1_shape': arg1_shape, 'arg2_value': arg2_value, 'arg3_value': arg3_value})
        return solver.check() == sat

    # Fuzz input generation phase
    else:
        rule_36(solver, {'arg1_ndim': arg1['ndim'], 'arg1_shape': arg1['shape'], 'arg2_value': arg2['value'], 'arg3_value': arg3['value']}, neg)
